#!/usr/bin/env bash
# Serve the site locally with live reload at http://localhost:4000
# Usage: docker/serve.sh [port]
#
# The theme builds every post link from site.url, so a preview served with the
# production config sends clicks to the live domain. This script writes a small
# dev config that points site.url at localhost for the preview only; the
# production build (docker/build.sh) is unaffected.
#
# Keep JEKYLL_ENV=production here (inherited from the image). In development
# mode Jekyll 3 overrides site.url with "http://<host>:<port>" (no trailing
# slash), which breaks the theme's links.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
IMAGE="longlinht-blog:jekyll"
PORT="${1:-4000}"
DEV_CONFIG="_config_dev.yml"   # gitignored, regenerated on every run

docker image inspect "$IMAGE" >/dev/null 2>&1 || "$ROOT/docker/build.sh"

cat > "$ROOT/$DEV_CONFIG" <<EOF
# Generated by docker/serve.sh for local preview. Do not commit.
url: 'http://localhost:${PORT}/'
EOF

docker run --rm -it \
  -u "$(id -u):$(id -g)" \
  -e HOME=/tmp \
  -v "$ROOT:/site" \
  -p "$PORT:4000" \
  "$IMAGE" \
  bundle exec jekyll serve --host 0.0.0.0 --port 4000 \
    --config "_config.yml,$DEV_CONFIG" \
    --watch --force_polling --drafts
